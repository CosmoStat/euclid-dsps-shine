def compare_synthetic_closure_to_reference(
    *,
    synthetic_path: str | Path,
    reference_path: str | Path,
    out_dir: str | Path,
    proposal_dir: str | Path | None = None,
    bands: Sequence[str] | None = None,
    max_reference: int | None = None,
    seed: int = 260617,
    plots: bool = True,
    reference_kind: str = "auto",
) -> dict[str, Path]:
    """Write population and photometry diagnostics for synthetic-vs-reference data.

    This is a population sanity comparison. The reference HLTDS photometry is
    Diffsky-generated, while the synthetic closure photometry is regenerated by
    euclid_dsps; the photometry metrics therefore diagnose gross consistency,
    not an exact closure equality.
    """
    synthetic_path = Path(synthetic_path)
    reference_path = Path(reference_path)
    out = ensure_dir(Path(out_dir))
    plot_dir = ensure_dir(out / "plots")
    band_names = tuple(bands or DEFAULT_BANDS)

    synthetic = pd.read_parquet(synthetic_path)
    reference = pd.read_parquet(reference_path)
    reference_kind = _infer_reference_kind(reference, reference_kind)
    reference = _standardize_reference_frame(reference, reference_kind)
    reference_label = _reference_display_name(reference_kind)
    if max_reference is not None and int(max_reference) > 0 and len(reference) > int(max_reference):
        reference = reference.sample(n=int(max_reference), random_state=int(seed))
    reference = reference.reset_index(drop=True)

    distribution_rows = _distribution_metrics(synthetic, reference)
    distribution_metrics = pd.DataFrame(distribution_rows)
    distribution_path = out / "distribution_metrics.csv"
    distribution_metrics.to_csv(distribution_path, index=False)

    photometry_rows = _photometry_metrics(synthetic, reference, band_names)
    photometry_metrics = pd.DataFrame(photometry_rows)
    photometry_path = out / "photometry_metrics.csv"
    photometry_metrics.to_csv(photometry_path, index=False)

    proposals = _load_proposals(Path(proposal_dir)) if proposal_dir else None
    proposal_metrics_path: Path | None = None
    proposal_metrics = pd.DataFrame()
    if proposals is not None:
        proposal_metrics = pd.DataFrame(_proposal_weighted_metrics(proposals))
        proposal_metrics_path = out / "proposal_weighted_metrics.csv"
        proposal_metrics.to_csv(proposal_metrics_path, index=False)

    correlation_payload = _correlation_report(synthetic, reference)
    correlation_path = out / "correlation_metrics.json"
    _write_json(correlation_path, correlation_payload)

    plot_paths: list[Path] = []
    if plots:
        plot_paths = _write_plots(
            synthetic,
            reference,
            distribution_metrics,
            photometry_metrics,
            plot_dir,
            reference_label=reference_label,
        )

    summary = _summary_payload(
        synthetic_path=synthetic_path,
        reference_path=reference_path,
        reference_kind=reference_kind,
        out_dir=out,
        synthetic=synthetic,
        reference=reference,
        bands=band_names,
        max_reference=max_reference,
        distribution_metrics=distribution_metrics,
        photometry_metrics=photometry_metrics,
        proposal_metrics=proposal_metrics,
        correlation_payload=correlation_payload,
        plot_paths=plot_paths,
        reference_label=reference_label,
    )
    summary_path = out / "comparison_summary.json"
    _write_json(summary_path, summary)

    report_path = out / "report.md"
    report_path.write_text(_markdown_report(summary), encoding="utf-8")
    return {
        "summary": summary_path,
        "report": report_path,
        "distribution_metrics": distribution_path,
        "photometry_metrics": photometry_path,
        "correlation_metrics": correlation_path,
        **({"proposal_weighted_metrics": proposal_metrics_path} if proposal_metrics_path else {}),
    }


def _distribution_metrics(
    synthetic: pd.DataFrame,
    reference: pd.DataFrame,
) -> list[dict[str, Any]]:
    rows = []
    for quantity, synthetic_column, reference_column in LATENT_COLUMN_PAIRS:
        rows.append(
            _metric_row_from_columns(
                "latent",
                quantity,
                synthetic,
                reference,
                synthetic_column,
                reference_column,
            )
        )
    return rows


def _infer_reference_kind(reference: pd.DataFrame, requested: str) -> str:
    requested = str(requested or "auto").lower()
    if requested != "auto":
        return requested
    columns = set(reference.columns)
    if {"z_true_gal", "log_stellar_mass", "lsst_u"} <= columns:
        return "fs2"
    return "hltds"


def _reference_display_name(reference_kind: str) -> str:
    kind = str(reference_kind or "reference").lower()
    if kind == "fs2":
        return "Euclid FS2 phz1"
    if kind == "hltds":
        return "HLTDS z<=0.35 reference"
    return f"{reference_kind} reference"


def _standardize_reference_frame(
    reference: pd.DataFrame,
    reference_kind: str,
) -> pd.DataFrame:
    if str(reference_kind).lower() != "fs2":
        return reference
    frame = reference.copy()
    if "redshift_true" not in frame and "z_true_gal" in frame:
        frame["redshift_true"] = pd.to_numeric(frame["z_true_gal"], errors="coerce")
    if "logsm_true" not in frame and "log_stellar_mass" in frame:
        frame["logsm_true"] = (
            pd.to_numeric(frame["log_stellar_mass"], errors="coerce")
            + 2.0 * np.log10(0.73)
        )
    if "logsfr_true" not in frame and "log_sfr_true" in frame:
        frame["logsfr_true"] = pd.to_numeric(frame["log_sfr_true"], errors="coerce")
    if "logssfr_true" not in frame and {"logsfr_true", "logsm_true"} <= set(frame.columns):
        frame["logssfr_true"] = frame["logsfr_true"] - frame["logsm_true"]
    if "dust_av" not in frame and "dust_ebv_true" in frame:
        frame["dust_av"] = 4.05 * pd.to_numeric(frame["dust_ebv_true"], errors="coerce")
    if "log10_stellar_metallicity" not in frame and "metallicity_true" in frame:
        frame["log10_stellar_metallicity"] = (
            pd.to_numeric(frame["metallicity_true"], errors="coerce") - 10.61
        )
    for band in FS2_FNU_CGS_BANDS:
        if band not in frame.columns:
            continue
        raw_flux = pd.to_numeric(frame[band], errors="coerce").to_numpy(dtype=float)
        if f"flux_{band}" not in frame.columns:
            frame[f"flux_{band}"] = raw_flux
        if f"mag_{band}" not in frame.columns:
            with np.errstate(divide="ignore", invalid="ignore"):
                mag = np.asarray(fnu_cgs_to_abmag(raw_flux), dtype=float)
            mag[~np.isfinite(raw_flux) | (raw_flux <= 0.0)] = np.nan
            frame[f"mag_{band}"] = mag
    return frame


def _reference_mag_column(reference: pd.DataFrame, band: str) -> str | None:
    for column in (f"mag_{band}", band, f"{band}_mag"):
        if column in reference.columns:
            return column
    return None


def _reference_flux_column(reference: pd.DataFrame, band: str) -> str | None:
    for column in (f"flux_{band}", f"{band}_flux"):
        if column in reference.columns:
            return column
    return None


def _reference_fluxerr_column(reference: pd.DataFrame, band: str) -> str | None:
    for column in (f"fluxerr_{band}", f"{band}_fluxerr", f"{band}_error"):
        if column in reference.columns:
            return column
    return None


def _reference_mask_column(reference: pd.DataFrame, band: str) -> str | None:
    for column in (f"mask_{band}", f"{band}_mask"):
        if column in reference.columns:
            return column
    return None


def _photometry_metrics(
    synthetic: pd.DataFrame,
    reference: pd.DataFrame,
    bands: Sequence[str],
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for band in bands:
        ref_mag_col = _reference_mag_column(reference, band)
        ref_flux_col = _reference_flux_column(reference, band)
        ref_err_col = _reference_fluxerr_column(reference, band)
        ref_mask_col = _reference_mask_column(reference, band)
        rows.append(
            _metric_row_from_columns(
                "mag_true_vs_reference_mag",
                band,
                synthetic,
                reference,
                f"mag_true_{band}",
                ref_mag_col or f"mag_{band}",
            )
        )
        rows.append(
            _metric_row_from_columns(
                "flux_true_vs_reference_flux",
                band,
                synthetic,
                reference,
                f"flux_true_{band}",
                ref_flux_col or f"flux_{band}",
            )
        )
        rows.append(
            _metric_row_from_columns(
                "flux_noisy_vs_reference_flux",
                band,
                synthetic,
                reference,
                f"flux_{band}",
                ref_flux_col or f"flux_{band}",
            )
        )
        rows.append(
            _metric_row_from_columns(
                "fluxerr",
                band,
                synthetic,
                reference,
                f"fluxerr_{band}",
                ref_err_col or f"fluxerr_{band}",
            )
        )
        rows.append(
            _metric_row_from_columns(
                "mask_fraction",
                band,
                synthetic,
                reference,
                f"mask_{band}",
                ref_mask_col or f"mask_{band}",
            )
        )
        syn_snr = _ratio_from_columns(synthetic, f"flux_{band}", f"fluxerr_{band}")
        ref_snr = (
            _ratio_from_columns(reference, ref_flux_col, ref_err_col)
            if ref_flux_col and ref_err_col
            else np.asarray([], dtype=float)
        )
        rows.append(
            _metric_row_from_arrays(
                "snr_observed",
                band,
                syn_snr,
                ref_snr,
                f"flux_{band}/fluxerr_{band}",
                (
                    f"{ref_flux_col}/{ref_err_col}"
                    if ref_flux_col and ref_err_col
                    else f"flux_{band}/fluxerr_{band}"
                ),
            )
        )
    for left, right in COLOR_PAIRS:
        if left not in bands or right not in bands:
            continue
        syn_color = _difference_from_columns(
            synthetic,
            f"mag_true_{left}",
            f"mag_true_{right}",
        )
        ref_left = _reference_mag_column(reference, left)
        ref_right = _reference_mag_column(reference, right)
        ref_color = (
            _difference_from_columns(reference, ref_left, ref_right)
            if ref_left and ref_right
            else np.asarray([], dtype=float)
        )
        rows.append(
            _metric_row_from_arrays(
                "color_true_vs_reference_color",
                f"{left}-{right}",
                syn_color,
                ref_color,
                f"mag_true_{left}-mag_true_{right}",
                f"{ref_left}-{ref_right}" if ref_left and ref_right else f"mag_{left}-mag_{right}",
            )
        )
    return rows


def _load_proposals(proposal_dir: Path) -> pd.DataFrame | None:
    if not proposal_dir.exists():
        return None
    paths = sorted(proposal_dir.glob("*/*.parquet"))
    if not paths:
        paths = sorted(proposal_dir.glob("*.parquet"))
    if not paths:
        return None
    return pd.concat([pd.read_parquet(path) for path in paths], ignore_index=True)


def _proposal_weighted_metrics(proposals: pd.DataFrame) -> list[dict[str, Any]]:
    if "galaxy_weight" not in proposals.columns:
        return []
    weights = _finite_numeric(proposals["galaxy_weight"])
    rows: list[dict[str, Any]] = []
    for quantity, column in (
        ("redshift", "redshift_true"),
        ("logsm", "logsm_true"),
        ("logsfr", "logsfr_true"),
        ("logssfr", "logssfr_true"),
        ("logmp", "logmp_true"),
        ("logmp0", "logmp0_true"),
        ("dust_av", "dust_av_true"),
        ("dust_delta", "dust_delta_true"),
        ("log10_stellar_metallicity", "log10_stellar_metallicity_true"),
    ):
        if column not in proposals.columns:
            continue
        values = pd.to_numeric(proposals[column], errors="coerce").to_numpy(dtype=float)
        raw_weights = pd.to_numeric(proposals["galaxy_weight"], errors="coerce").to_numpy(
            dtype=float
        )
        finite = np.isfinite(values) & np.isfinite(raw_weights) & (raw_weights > 0.0)
        values = values[finite]
        raw_weights = raw_weights[finite]
        row: dict[str, Any] = {
            "quantity": quantity,
            "column": column,
            "n": int(values.size),
            "weight_sum": float(np.sum(raw_weights)) if values.size else np.nan,
        }
        row.update(_prefixed_stats("unweighted", values))
        row.update(_weighted_stats("weighted", values, raw_weights))
        if quantity == "logsm":
            for threshold in (5.0, 7.0, 8.0, 9.0, 10.0):
                row[f"unweighted_fraction_ge_{threshold:g}"] = float(
                    np.mean(values >= threshold)
                )
                row[f"weighted_fraction_ge_{threshold:g}"] = float(
                    np.sum(raw_weights[values >= threshold]) / np.sum(raw_weights)
                )
        rows.append(row)
    return rows


def _weighted_stats(prefix: str, values: np.ndarray, weights: np.ndarray) -> dict[str, float]:
    values = _finite_array(values)
    weights = _finite_array(weights)
    n = min(values.size, weights.size)
    values = values[:n]
    weights = weights[:n]
    finite = np.isfinite(values) & np.isfinite(weights) & (weights > 0.0)
    values = values[finite]
    weights = weights[finite]
    if values.size == 0 or np.sum(weights) <= 0.0:
        return {
            f"{prefix}_mean": np.nan,
            f"{prefix}_q05": np.nan,
            f"{prefix}_q16": np.nan,
            f"{prefix}_median": np.nan,
            f"{prefix}_q84": np.nan,
            f"{prefix}_q95": np.nan,
        }
    return {
        f"{prefix}_mean": float(np.sum(values * weights) / np.sum(weights)),
        f"{prefix}_q05": float(_weighted_quantile(values, weights, 0.05)),
        f"{prefix}_q16": float(_weighted_quantile(values, weights, 0.16)),
        f"{prefix}_median": float(_weighted_quantile(values, weights, 0.5)),
        f"{prefix}_q84": float(_weighted_quantile(values, weights, 0.84)),
        f"{prefix}_q95": float(_weighted_quantile(values, weights, 0.95)),
    }


def _weighted_quantile(values: np.ndarray, weights: np.ndarray, quantile: float) -> float:
    order = np.argsort(values)
    values = values[order]
    weights = weights[order]
    cumulative = np.cumsum(weights)
    if cumulative[-1] <= 0.0:
        return np.nan
    cumulative = cumulative / cumulative[-1]
    return float(values[np.searchsorted(cumulative, float(quantile), side="left")])


def _metric_row_from_columns(
    group: str,
    quantity: str,
    synthetic: pd.DataFrame,
    reference: pd.DataFrame,
    synthetic_column: str,
    reference_column: str,
) -> dict[str, Any]:
    if synthetic_column not in synthetic.columns or reference_column not in reference.columns:
        return _missing_row(
            group,
            quantity,
            synthetic_column,
            reference_column,
            synthetic_column in synthetic.columns,
            reference_column in reference.columns,
        )
    return _metric_row_from_arrays(
        group,
        quantity,
        _finite_numeric(synthetic[synthetic_column]),
        _finite_numeric(reference[reference_column]),
        synthetic_column,
        reference_column,
    )


def _metric_row_from_arrays(
    group: str,
    quantity: str,
    synthetic_values: np.ndarray,
    reference_values: np.ndarray,
    synthetic_column: str,
    reference_column: str,
) -> dict[str, Any]:
    synthetic_values = _finite_array(synthetic_values)
    reference_values = _finite_array(reference_values)
    status = "ok"
    if synthetic_values.size < 2 or reference_values.size < 2:
        status = "insufficient_finite"
    row: dict[str, Any] = {
        "group": group,
        "quantity": quantity,
        "synthetic_column": synthetic_column,
        "reference_column": reference_column,
        "status": status,
        "synthetic_n": int(synthetic_values.size),
        "reference_n": int(reference_values.size),
    }
    row.update(_prefixed_stats("synthetic", synthetic_values))
    row.update(_prefixed_stats("reference", reference_values))
    row["delta_mean"] = _delta(row.get("synthetic_mean"), row.get("reference_mean"))
    row["delta_median"] = _delta(
        row.get("synthetic_median"),
        row.get("reference_median"),
    )
    if status == "ok":
        row["ks"] = float(_ks_distance(synthetic_values, reference_values))
        row["wasserstein_quantile"] = float(
            _wasserstein_quantile(synthetic_values, reference_values)
        )
    else:
        row["ks"] = np.nan
        row["wasserstein_quantile"] = np.nan
    return row


def _missing_row(
    group: str,
    quantity: str,
    synthetic_column: str,
    reference_column: str,
    has_synthetic: bool,
    has_reference: bool,
) -> dict[str, Any]:
    if not has_synthetic and not has_reference:
        status = "missing_both"
    elif not has_synthetic:
        status = "missing_synthetic"
    else:
        status = "missing_reference"
    row: dict[str, Any] = {
        "group": group,
        "quantity": quantity,
        "synthetic_column": synthetic_column,
        "reference_column": reference_column,
        "status": status,
        "synthetic_n": 0,
        "reference_n": 0,
        "ks": np.nan,
        "wasserstein_quantile": np.nan,
        "delta_mean": np.nan,
        "delta_median": np.nan,
    }
    row.update(_prefixed_stats("synthetic", np.asarray([], dtype=float)))
    row.update(_prefixed_stats("reference", np.asarray([], dtype=float)))
    return row


def _prefixed_stats(prefix: str, values: np.ndarray) -> dict[str, float]:
    if values.size == 0:
        return {
            f"{prefix}_mean": np.nan,
            f"{prefix}_std": np.nan,
            f"{prefix}_min": np.nan,
            f"{prefix}_q01": np.nan,
            f"{prefix}_q05": np.nan,
            f"{prefix}_q16": np.nan,
            f"{prefix}_median": np.nan,
            f"{prefix}_q84": np.nan,
            f"{prefix}_q95": np.nan,
            f"{prefix}_q99": np.nan,
            f"{prefix}_max": np.nan,
        }
    quantiles = np.quantile(values, [0.01, 0.05, 0.16, 0.5, 0.84, 0.95, 0.99])
    return {
        f"{prefix}_mean": float(np.mean(values)),
        f"{prefix}_std": float(np.std(values)),
        f"{prefix}_min": float(np.min(values)),
        f"{prefix}_q01": float(quantiles[0]),
        f"{prefix}_q05": float(quantiles[1]),
        f"{prefix}_q16": float(quantiles[2]),
        f"{prefix}_median": float(quantiles[3]),
        f"{prefix}_q84": float(quantiles[4]),
        f"{prefix}_q95": float(quantiles[5]),
        f"{prefix}_q99": float(quantiles[6]),
        f"{prefix}_max": float(np.max(values)),
    }


def _delta(left: Any, right: Any) -> float:
    try:
        left_value = float(left)
        right_value = float(right)
    except (TypeError, ValueError):
        return np.nan
    if not np.isfinite(left_value) or not np.isfinite(right_value):
        return np.nan
    return left_value - right_value


def _finite_numeric(series: pd.Series) -> np.ndarray:
    if pd.api.types.is_bool_dtype(series):
        arr = series.astype(float).to_numpy()
    else:
        arr = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    return _finite_array(arr)


def _finite_array(values: Iterable[float] | np.ndarray) -> np.ndarray:
    arr = np.asarray(values, dtype=float).reshape(-1)
    return arr[np.isfinite(arr)]


def _ratio_from_columns(frame: pd.DataFrame, numerator: str, denominator: str) -> np.ndarray:
    if numerator not in frame.columns or denominator not in frame.columns:
        return np.asarray([], dtype=float)
    num = pd.to_numeric(frame[numerator], errors="coerce").to_numpy(dtype=float)
    den = pd.to_numeric(frame[denominator], errors="coerce").to_numpy(dtype=float)
    finite = np.isfinite(num) & np.isfinite(den)
    if not np.any(finite):
        return np.asarray([], dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        return _finite_array(num[finite] / den[finite])


def _difference_from_columns(frame: pd.DataFrame, left: str, right: str) -> np.ndarray:
    if left not in frame.columns or right not in frame.columns:
        return np.asarray([], dtype=float)
    left_values = pd.to_numeric(frame[left], errors="coerce").to_numpy(dtype=float)
    right_values = pd.to_numeric(frame[right], errors="coerce").to_numpy(dtype=float)
    return _finite_array(left_values - right_values)


def _ks_distance(left: np.ndarray, right: np.ndarray) -> float:
    left = np.sort(_finite_array(left))
    right = np.sort(_finite_array(right))
    if left.size == 0 or right.size == 0:
        return np.nan
    values = np.sort(np.concatenate([left, right]))
    left_cdf = np.searchsorted(left, values, side="right") / left.size
    right_cdf = np.searchsorted(right, values, side="right") / right.size
    return float(np.max(np.abs(left_cdf - right_cdf)))


def _wasserstein_quantile(left: np.ndarray, right: np.ndarray, n_grid: int = 1001) -> float:
    left = _finite_array(left)
    right = _finite_array(right)
    if left.size == 0 or right.size == 0:
        return np.nan
    q = np.linspace(0.0, 1.0, int(n_grid))
    return float(np.mean(np.abs(np.quantile(left, q) - np.quantile(right, q))))


def _correlation_report(
    synthetic: pd.DataFrame,
    reference: pd.DataFrame,
) -> dict[str, Any]:
    labels: list[str] = []
    synthetic_columns: list[str] = []
    reference_columns: list[str] = []
    for quantity, synthetic_column, reference_column in LATENT_COLUMN_PAIRS:
        if synthetic_column in synthetic.columns and reference_column in reference.columns:
            syn_values = _finite_numeric(synthetic[synthetic_column])
            ref_values = _finite_numeric(reference[reference_column])
            if syn_values.size >= 3 and ref_values.size >= 3:
                labels.append(quantity)
                synthetic_columns.append(synthetic_column)
                reference_columns.append(reference_column)
    if len(labels) < 2:
        return {
            "status": "insufficient_columns",
            "labels": labels,
            "correlation_frobenius_error": np.nan,
        }
    syn_matrix = _finite_matrix(synthetic, synthetic_columns)
    ref_matrix = _finite_matrix(reference, reference_columns)
    if syn_matrix.shape[0] < 3 or ref_matrix.shape[0] < 3:
        return {
            "status": "insufficient_rows",
            "labels": labels,
            "synthetic_rows": int(syn_matrix.shape[0]),
            "reference_rows": int(ref_matrix.shape[0]),
            "correlation_frobenius_error": np.nan,
        }
    nonconstant = (np.std(syn_matrix, axis=0) > 0.0) & (
        np.std(ref_matrix, axis=0) > 0.0
    )
    if np.count_nonzero(nonconstant) < 2:
        return {
            "status": "insufficient_nonconstant_columns",
            "labels": labels,
            "synthetic_rows": int(syn_matrix.shape[0]),
            "reference_rows": int(ref_matrix.shape[0]),
            "correlation_frobenius_error": np.nan,
        }
    labels = [label for label, keep in zip(labels, nonconstant, strict=True) if keep]
    synthetic_columns = [
        column for column, keep in zip(synthetic_columns, nonconstant, strict=True) if keep
    ]
    reference_columns = [
        column for column, keep in zip(reference_columns, nonconstant, strict=True) if keep
    ]
    syn_matrix = syn_matrix[:, nonconstant]
    ref_matrix = ref_matrix[:, nonconstant]
    syn_corr = np.corrcoef(syn_matrix, rowvar=False)
    ref_corr = np.corrcoef(ref_matrix, rowvar=False)
    diff = syn_corr - ref_corr
    return {
        "status": "ok",
        "labels": labels,
        "synthetic_columns": synthetic_columns,
        "reference_columns": reference_columns,
        "synthetic_rows": int(syn_matrix.shape[0]),
        "reference_rows": int(ref_matrix.shape[0]),
        "correlation_frobenius_error": float(np.linalg.norm(diff)),
        "correlation_mean_abs_error": float(np.mean(np.abs(diff))),
        "synthetic_correlation": syn_corr,
        "reference_correlation": ref_corr,
        "correlation_difference": diff,
    }


def _finite_matrix(frame: pd.DataFrame, columns: Sequence[str]) -> np.ndarray:
    data = frame.loc[:, list(columns)].apply(pd.to_numeric, errors="coerce")
    matrix = data.to_numpy(dtype=float)
    finite = np.isfinite(matrix).all(axis=1)
    return matrix[finite]


