def _top_metric_rows(
    frame: pd.DataFrame,
    metric: str,
    *,
    n: int,
    absolute: bool = False,
) -> list[dict[str, Any]]:
    if frame.empty or metric not in frame.columns:
        return []
    ok = frame[frame["status"] == "ok"].copy()
    ok = ok[np.isfinite(pd.to_numeric(ok[metric], errors="coerce"))]
    if ok.empty:
        return []
    score = pd.to_numeric(ok[metric], errors="coerce").abs() if absolute else pd.to_numeric(ok[metric], errors="coerce")
    ok = ok.assign(_score=score).sort_values("_score", ascending=False).head(int(n))
    return ok.drop(columns=["_score"]).to_dict(orient="records")


def _reference_photometry_units(
    reference: pd.DataFrame,
    bands: Sequence[str],
) -> dict[str, dict[str, Any]]:
    payload: dict[str, dict[str, Any]] = {}
    for band in bands:
        mag_column = _reference_mag_column(reference, band)
        flux_column = _reference_flux_column(reference, band)
        if not mag_column and not flux_column:
            continue
        payload[band] = {
            "mag_column": mag_column,
            "flux_column": flux_column,
            "mag_from_flux": bool(
                mag_column == f"mag_{band}"
                and flux_column == f"flux_{band}"
                and band in reference.columns
            ),
            "flux_units": "fnu_cgs" if flux_column else None,
            "mag_units": "AB" if mag_column else None,
        }
    return payload


