import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pandas as pd

from euclid_dsps.amortized.config import require_amortized_dependencies
from euclid_dsps.amortized.elbo import AmortizedModel
from euclid_dsps.amortized.features import read_feature_stats
from euclid_dsps.amortized.latent import latent_spec_from_config, theta_to_x
from euclid_dsps.amortized.npe_validation import assert_truth_free_columns
from euclid_dsps.amortized.population_vem import sha256_file
from euclid_dsps.amortized.population_vi import (
    frozen_proposal_population_objective,
    population_prior_value_and_grad,
)
from euclid_dsps.amortized.posthoc_calibration import load_posterior_bank
from euclid_dsps.amortized.train import (
    _selection_correction_runtime_config,
    _selection_log_beta_from_prior_samples,
    load_checkpoint,
    save_checkpoint,
)
from euclid_dsps.config import load_config
